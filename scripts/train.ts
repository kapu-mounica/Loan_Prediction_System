/**
 * Training pipeline (run with `bun scripts/train.ts`).
 *
 * 1. Generate the deterministic simulated loan dataset (seed 42)
 * 2. Train + evaluate Logistic Regression and Random Forest on a stratified
 *    80/20 split, select the better model by ROC-AUC
 * 3. Persist:
 *    - backend/dataset/loan_dataset.csv      (shared with the Python backend)
 *    - src/convex/loanData.ts                (dataset for the retrain endpoint)
 *    - src/ml/artifacts/model.json           (the model artifact)
 *    - src/convex/loanModel.ts               (artifact embedded for the API)
 */

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { generateLoanDataset, rowsToCsv } from "../src/ml/dataset";
import { trainAndEvaluate } from "../src/ml/train";
import type { ModelArtifact } from "../src/ml/types";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

function main() {
  console.log("Loan Risk Assessment — model training pipeline\n");

  console.log("1. Generating dataset (deterministic, seed=42)...");
  const rows = generateLoanDataset(1500, 42);

  console.log("2. Training and evaluating models...");
  const { artifact, report } = trainAndEvaluate(rows, { seed: 42, testSize: 0.2 });
  console.log("\n" + report);

  const csvDir = resolve(ROOT, "backend/dataset");
  mkdirSync(csvDir, { recursive: true });
  writeFileSync(resolve(csvDir, "loan_dataset.csv"), rowsToCsv(rows), "utf8");

  const convexData = `// Generated by scripts/train.ts — do not edit by hand.\n// Loan dataset rows (COLUMNS order, null = missing value).\nexport type LoanRow = (number | string | null)[];\nexport const LOAN_DATASET: LoanRow[] = ${JSON.stringify(rows)};\n`;
  mkdirSync(resolve(ROOT, "src/convex"), { recursive: true });
  writeFileSync(resolve(ROOT, "src/convex/loanData.ts"), convexData, "utf8");

  // Embed the artifact as a JSON string so the Convex bundle stays small and
  // type-safe (parsed at runtime; no giant inferred literal types).
  const modelModule = `// Generated by scripts/train.ts — do not edit by hand.\n// Serialized model artifact (see src/ml/artifacts/model.json).\nexport const MODEL_JSON: string = ${JSON.stringify(JSON.stringify(artifact))};\n`;
  writeFileSync(resolve(ROOT, "src/convex/loanModel.ts"), modelModule, "utf8");

  const outDir = resolve(ROOT, "src/ml/artifacts");
  mkdirSync(outDir, { recursive: true });
  writeFileSync(resolve(outDir, "model.json"), JSON.stringify(artifact), "utf8");

  console.log("\n3. Wrote artifacts:");
  console.log("   - backend/dataset/loan_dataset.csv");
  console.log("   - src/convex/loanData.ts");
  console.log("   - src/ml/artifacts/model.json");
  console.log("   - src/convex/loanModel.ts");
}

main();

export type { ModelArtifact };
